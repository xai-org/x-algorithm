#!/usr/bin/env python3
"""Generate a changelog of `param!` default changes between syncs.

Usage:
    # What changed between two commits (Markdown to stdout)
    home-mixer/scripts/param_changelog.py diff b089ce6 6bb4594

    # Regenerate docs/PARAM_CHANGES.md from git history, keeping
    # hand-written plain-language notes
    home-mixer/scripts/param_changelog.py history --output docs/PARAM_CHANGES.md

Only the standard library and `git` are required.
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
from dataclasses import dataclass
from datetime import datetime, timezone
from pathlib import Path

DEFAULT_FILES = ("home-mixer/params/param.rs", "vm-ranker/params.rs")
DEFAULT_REPO_URL = "https://github.com/xai-org/x-algorithm"
SYNC_HEADER_RE = re.compile(r"^//.*last sync .*$", re.MULTILINE)
NOTE_RE = re.compile(r"<!-- note:([0-9a-f]+) -->\n(.*?)<!-- /note -->", re.DOTALL)
NOTE_PLACEHOLDER = "_Plain-language explanation pending._\n"
DOC_HEADER = """\
# Parameter changes

Every change to a `param!` default in {files}, one section per sync, newest first.
Generated by
[`home-mixer/scripts/param_changelog.py`](../home-mixer/scripts/param_changelog.py) —
do not edit the tables by hand.

These defaults are the primary production values (see
[Experiments and Configuration](../README.md#experiments-and-configuration)). A weight
multiplies the *predicted* probability of an action, not raw engagement counts.

To explain a change, replace the placeholder between that section's `<!-- note:… -->`
markers. Notes are kept when the file is regenerated.
"""


@dataclass(frozen=True)
class Param:
    name: str
    type: str
    key: str
    default: str


@dataclass(frozen=True)
class Change:
    name: str
    old: Param | None
    new: Param | None


def _strip_comments(src: str) -> str:
    """Remove `//` and `/* */` comments, leaving string literals intact."""
    out = []
    i, n = 0, len(src)
    while i < n:
        c = src[i]
        if c == '"':
            j = i + 1
            while j < n and src[j] != '"':
                j += 2 if src[j] == "\\" else 1
            out.append(src[i : j + 1])
            i = j + 1
        elif src.startswith("//", i):
            while i < n and src[i] != "\n":
                i += 1
        elif src.startswith("/*", i):
            end = src.find("*/", i + 2)
            i = n if end == -1 else end + 2
        else:
            out.append(c)
            i += 1
    return "".join(out)


def _split_top_level(body: str) -> list[str]:
    """Split macro arguments on commas outside brackets and strings."""
    parts, depth, cur = [], 0, []
    i, n = 0, len(body)
    while i < n:
        c = body[i]
        if c == '"':
            j = i + 1
            while j < n and body[j] != '"':
                j += 2 if body[j] == "\\" else 1
            cur.append(body[i : j + 1])
            i = j + 1
            continue
        if c in "([{<":
            depth += 1
        elif c in ")]}>":
            depth -= 1
        if c == "," and depth == 0:
            parts.append("".join(cur))
            cur = []
        else:
            cur.append(c)
        i += 1
    if "".join(cur).strip():
        parts.append("".join(cur))
    return [" ".join(p.split()) for p in parts]


def parse_params(src: str) -> dict[str, Param]:
    """Parse every `param!(Name, Type, "key", default)` in a Rust source file."""
    src = _strip_comments(src)
    params: dict[str, Param] = {}
    for m in re.finditer(r"\bparam!\s*\(", src):
        i, depth = m.end(), 1
        while i < len(src) and depth:
            c = src[i]
            if c == '"':
                i += 1
                while i < len(src) and src[i] != '"':
                    i += 2 if src[i] == "\\" else 1
            elif c == "(":
                depth += 1
            elif c == ")":
                depth -= 1
            i += 1
        args = _split_top_level(src[m.end() : i - 1])
        if len(args) < 4:
            continue
        name, key, default = args[0], args[-2], args[-1]
        params[name] = Param(name, ", ".join(args[1:-2]), key.strip('"'), default)
    return params


def diff_params(old: dict[str, Param], new: dict[str, Param]) -> list[Change]:
    changes = [Change(name, old.get(name), p) for name, p in new.items() if old.get(name) != p]
    changes += [Change(name, p, None) for name, p in old.items() if name not in new]
    return changes


def _git(*args: str) -> str:
    return subprocess.run(["git", *args], check=True, capture_output=True, text=True).stdout


def file_at(rev: str, path: str) -> str | None:
    try:
        return _git("show", f"{rev}:{path}")
    except subprocess.CalledProcessError:
        return None


def commit_date(rev: str) -> datetime:
    iso = _git("show", "-s", "--format=%cI", rev).strip()
    return datetime.fromisoformat(iso).astimezone(timezone.utc)


def commits_touching(files: list[str], since: str | None) -> list[str]:
    args = ["log", "--first-parent", "--format=%H"]
    if since:
        args.append(f"--since={since}")
    return _git(*args, "--", *files).split()


def _cell(p: Param | None) -> str:
    return "—" if p is None else f"`{p.default}`".replace("|", "\\|")


def _new_cell(c: Change) -> str:
    cell = _cell(c.new)
    if c.old and c.new:
        if c.old.type != c.new.type:
            cell += f" (type `{c.old.type}` → `{c.new.type}`)"
        if c.old.key != c.new.key:
            cell += f" (key `{c.old.key}` → `{c.new.key}`)"
    return cell


def _is_weight(name: str) -> bool:
    return "Weight" in name


@dataclass
class FileDiff:
    path: str
    status: str  # "changed", "added", "header-only", "no-param-change", "unchanged"
    changes: list[Change]
    param_count: int = 0


def diff_file(old_rev: str, new_rev: str, path: str) -> FileDiff:
    old_src, new_src = file_at(old_rev, path), file_at(new_rev, path)
    if new_src is None or old_src == new_src:
        return FileDiff(path, "unchanged", [])
    if old_src is None:
        return FileDiff(path, "added", [], len(parse_params(new_src)))
    changes = diff_params(parse_params(old_src), parse_params(new_src))
    if changes:
        return FileDiff(path, "changed", changes)
    if SYNC_HEADER_RE.sub("", old_src) == SYNC_HEADER_RE.sub("", new_src):
        return FileDiff(path, "header-only", [])
    return FileDiff(path, "no-param-change", [])


def render_file_diff(fd: FileDiff) -> str:
    if fd.status == "added":
        return f"#### `{fd.path}`\n\nFirst published with {fd.param_count} parameters.\n"
    if fd.status != "changed":
        return ""
    rows = [f"| `{c.name}` | {_cell(c.old)} | {_new_cell(c)} |" for c in fd.changes]
    return "\n".join([f"#### `{fd.path}`", "", "| Param | Old | New |", "|---|---|---|", *rows, ""])


def render_sync(rev: str, files: list[str], repo_url: str, notes: dict[str, str]) -> str | None:
    """Render one sync's section, or None if none of `files` changed."""
    sha = _git("rev-parse", rev).strip()
    parent = f"{sha}^"
    diffs = [diff_file(parent, sha, f) for f in files]
    diffs = [d for d in diffs if d.status != "unchanged"]
    if not diffs:
        return None

    date = commit_date(sha).strftime("%Y-%m-%d %H:%M UTC")
    short = sha[:7]
    heading = f"## {date} ([`{short}`]({repo_url}/commit/{sha}))\n"
    body = [render_file_diff(d) for d in diffs]
    body = [b for b in body if b]

    if not body:
        if all(d.status == "header-only" for d in diffs):
            return heading + "\n_Sync timestamp only; no parameter changes._\n"
        return heading + "\n_Comments or formatting only; no parameter value changes._\n"

    touches_weight = any(_is_weight(c.name) for d in diffs for c in d.changes)
    note = notes.get(short, NOTE_PLACEHOLDER if touches_weight else "")
    return "\n".join([heading, *body, f"<!-- note:{short} -->\n{note}<!-- /note -->", ""])


def read_notes(path: Path) -> dict[str, str]:
    if not path.exists():
        return {}
    return {sha: text for sha, text in NOTE_RE.findall(path.read_text())}


def cmd_diff(args: argparse.Namespace) -> int:
    any_change = False
    for path in args.file:
        fd = diff_file(args.old, args.new, path)
        out = render_file_diff(fd)
        if out:
            any_change = True
            print(out)
    if not any_change:
        print("No parameter changes.")
    return 0


def cmd_history(args: argparse.Namespace) -> int:
    output = Path(args.output) if args.output else None
    notes = read_notes(output) if output else {}
    sections = [
        s
        for rev in commits_touching(args.file, args.since)
        if (s := render_sync(rev, args.file, args.repo_url, notes))
    ]
    files = ", ".join(f"[`{f}`](../{f})" for f in args.file)
    doc = DOC_HEADER.format(files=files) + "\n" + "\n".join(sections)
    if output:
        output.write_text(doc)
    else:
        sys.stdout.write(doc)
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument(
        "--file",
        action="append",
        help=f"Param file to track (repeatable; default: {', '.join(DEFAULT_FILES)})",
    )
    sub = parser.add_subparsers(dest="command", required=True)

    p_diff = sub.add_parser("diff", help="Param changes between two revisions")
    p_diff.add_argument("old")
    p_diff.add_argument("new", nargs="?", default="HEAD")
    p_diff.set_defaults(func=cmd_diff)

    p_hist = sub.add_parser("history", help="Changelog for every sync")
    p_hist.add_argument("--since", help="Only commits after this date, e.g. 2026-08-01")
    p_hist.add_argument("--output", help="Write here, keeping existing notes")
    p_hist.add_argument("--repo-url", default=DEFAULT_REPO_URL)
    p_hist.set_defaults(func=cmd_history)

    args = parser.parse_args(argv)
    args.file = args.file or list(DEFAULT_FILES)
    return args.func(args)


if __name__ == "__main__":
    sys.exit(main())
