#[cfg(test)]
mod tests {
    use super::*;
    use crate::hydration::Relation;
    use crate::rules::SafetyLevel;
    use strum::VariantArray;

    #[test]
    fn a_level_lists_all_of_the_reacted_to_rules_exactly_when_it_reads_the_relation() {
        let reading = |level: SafetyLevel| -> Vec<&'static Rule> {
            level
                .spec()
                .rules()
                .lists()
                .post_rules()
                .filter(|rule| {
                    rule.requirements()
                        .iter()
                        .any(|node| node.relation() == Some(Relation::ReactedTo))
                })
                .collect()
        };
        let mut rules: Vec<&Rule> = SafetyLevel::VARIANTS
            .iter()
            .flat_map(|&level| reading(level))
            .collect();
        rules.sort_by_key(|rule| rule.name());
        rules.dedup_by_key(|rule| rule.name());
        assert!(!rules.is_empty(), "no level reads the reacted-to post");
        for &level in SafetyLevel::VARIANTS {
            let listed = reading(level).len();
            assert!(
                listed == 0 || listed == rules.len(),
                "{level:?} lists part of the reacted-to rules"
            );
        }
    }

    #[test]
    fn timeline_home_recommendations_starts_with_timeline_home() {
        let (home, recommendations) =
            (TIMELINE_HOME.lists(), TIMELINE_HOME_RECOMMENDATIONS.lists());
        assert!(recommendations.user.starts_with(&home.user));
        assert!(recommendations.post.starts_with(&home.post));
    }
}
